-- ==============================================================================
-- ENTREGA 2 - SCRIPT 1: PAQUETE PKG_TURISMOUQ
-- Proyecto Integrador Bases de Datos II - TurismoUQ
-- ------------------------------------------------------------------------------
-- Que hacemos en este script:
--   Creamos una tabla de apoyo (LIQUIDACION_MENSUAL) y un paquete con 3 cosas:
--     1. fn_valor_estadia, para calcular cuanto cuesta una estadia, noche por noche
--     2. sp_crear_reserva, para crear una reserva validando fechas, capacidad y disponibilidad
--     3. sp_liquidacion_mensual para calcular lo que le toca a cada alojamiento en un mes (usa cursor con parametros)
--
--
-- Errores propios que lanza el paquete (RAISE_APPLICATION_ERROR):
--   -20001  habitacion no disponible (se cruza con otra reserva)
--   -20002  fechas malas (checkout igual o anterior al checkin, o mas de 30 noches)
--   -20003  capacidad excedida (mas huespedes de los que caben)
--   -20004  no hay tarifa para esa habitacion en esa fecha
--   -20005  la habitacion o el alojamiento no existen
--   -20006  hay temporadas que se cruzan entre si (datos mal cargados)
--   -20007  el check-in esta en el pasado
-- ==============================================================================


-- ==============================================================================
-- 1. TABLA LIQUIDACION_MENSUAL
-- Aqui guardamos el resultado de la liquidacion: una fila por alojamiento y por mes.
-- El UNIQUE (alojamiento, anio, mes) evita que un mismo mes se liquide dos veces
-- para el mismo alojamiento.
-- ==============================================================================
CREATE TABLE LIQUIDACION_MENSUAL (
    id_liquidacion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_alojamiento NUMBER(5) NOT NULL,
    anio NUMBER(4) NOT NULL,
    mes NUMBER(2) NOT NULL CHECK (mes BETWEEN 1 AND 12),   -- solo meses de 1 a 12
    total_noches NUMBER(10) DEFAULT 0,
    ingresos_hospedaje NUMBER(14) DEFAULT 0,
    ingresos_servicios NUMBER(14) DEFAULT 0,
    total_liquidacion NUMBER(14) DEFAULT 0,                -- hospedaje + servicios
    fecha_liquidacion DATE DEFAULT SYSDATE,
    CONSTRAINT uk_liq UNIQUE (id_alojamiento, anio, mes),
    CONSTRAINT fk_liq_aloj FOREIGN KEY (id_alojamiento) REFERENCES ALOJAMIENTO(id_alojamiento)
);


-- ==============================================================================
-- 2. ESPECIFICACION DEL PAQUETE
-- Es como la "vitrina" del paquete: dice que funciones y procedimientos tiene y que
-- parametros reciben, pero no el codigo (el codigo va en el cuerpo, mas abajo).
-- ==============================================================================
CREATE OR REPLACE PACKAGE PKG_TURISMOUQ AS

    -- Calcula el valor de una estadia noche por noche (cada noche con la tarifa de SU temporada)
    FUNCTION fn_valor_estadia(
        p_id_habitacion IN NUMBER,
        p_fecha_in      IN DATE,
        p_fecha_out     IN DATE
    ) RETURN NUMBER;

    -- Crea una reserva con una habitacion. Devuelve el id de la reserva creada en p_id_reserva
    PROCEDURE sp_crear_reserva(
        p_id_cliente     IN NUMBER,
        p_id_alojamiento IN NUMBER,
        p_id_habitacion  IN NUMBER,
        p_check_in       IN DATE,
        p_check_out      IN DATE,
        p_num_huespedes  IN NUMBER,
        p_id_reserva     OUT NUMBER
    );

    -- Liquidacion de un mes: recibe el anio y el mes y llena LIQUIDACION_MENSUAL
    PROCEDURE sp_liquidacion_mensual(
        p_anio IN NUMBER,
        p_mes  IN NUMBER
    );

END PKG_TURISMOUQ;
/


-- ==============================================================================
-- 3. CUERPO DEL PAQUETE
-- Aqui esta el codigo de verdad de cada funcion y procedimiento.
-- ==============================================================================
CREATE OR REPLACE PACKAGE BODY PKG_TURISMOUQ AS

    -- --------------------------------------------------------------------------
    -- fn_valor_estadia
    -- Es la funcion mas importante: una estadia puede empezar en una temporada y terminar
    -- en otra (por ejemplo, entrar el 13 de dic en temporada media y salir el 17 ya en alta).
    -- Entonces no sirve multiplicar noches x un solo precio. Lo que hacemos es recorrer
    -- cada noche, buscar en que temporada cae y sumar la tarifa de esa temporada.
    -- La noche del check-out no se cobra (por eso el ciclo va hasta antes del check-out).
    -- --------------------------------------------------------------------------
    FUNCTION fn_valor_estadia(
        p_id_habitacion IN NUMBER,
        p_fecha_in      IN DATE,
        p_fecha_out     IN DATE
    ) RETURN NUMBER IS
        v_total  NUMBER(12) := 0;           -- aqui se va acumulando el valor
        v_dia    DATE := TRUNC(p_fecha_in); -- la noche que estamos revisando (arranca en el check-in)
        v_tarifa NUMBER(10);                -- tarifa de esa noche
    BEGIN
        -- si el checkout es igual o anterior al checkin no tiene sentido calcular nada
        IF p_fecha_out <= p_fecha_in THEN
            RAISE_APPLICATION_ERROR(-20002, 'CHECKOUT debe ser posterior al CHECKIN. In: '
                || TO_CHAR(p_fecha_in, 'YYYY-MM-DD') || ' Out: ' || TO_CHAR(p_fecha_out, 'YYYY-MM-DD'));
        END IF;

        -- recorremos noche por noche, desde el check-in hasta la noche anterior al check-out
        WHILE v_dia < TRUNC(p_fecha_out) LOOP
            BEGIN
                -- buscamos la tarifa de esta habitacion en la temporada donde cae esta noche
                -- (fecha_fin es inclusiva, por eso comparamos con fecha_fin + 1)
                SELECT ta.valor_noche
                INTO v_tarifa
                FROM TEMPORADA t
                JOIN TARIFA ta ON ta.id_temporada = t.id_temporada
                WHERE ta.id_habitacion = p_id_habitacion
                  AND v_dia >= t.fecha_inicio
                  AND v_dia < t.fecha_fin + 1;
            EXCEPTION
                -- ninguna temporada cubre ese dia, o la habitacion no tiene tarifa
                WHEN NO_DATA_FOUND THEN
                    RAISE_APPLICATION_ERROR(-20004, 'No hay tarifa definida para habitacion ' || p_id_habitacion
                        || ' en la fecha ' || TO_CHAR(v_dia, 'YYYY-MM-DD'));
                -- mas de una temporada cubre ese dia (las temporadas estan cruzadas)
                WHEN TOO_MANY_ROWS THEN
                    RAISE_APPLICATION_ERROR(-20006, 'Hay temporadas solapadas en la fecha ' || TO_CHAR(v_dia, 'YYYY-MM-DD'));
            END;

            v_total := v_total + v_tarifa;  -- sumamos la noche
            v_dia := v_dia + 1;             -- pasamos a la siguiente noche
        END LOOP;

        RETURN v_total;
    END fn_valor_estadia;


    -- --------------------------------------------------------------------------
    -- sp_crear_reserva
    -- Valida todo y, si esta bien, crea la reserva (cabecera en RESERVA y detalle en
    -- RESERVA_HABITACION). Si algo falla en el camino, se deshace todo para que no quede
    -- una reserva a medias.
    -- --------------------------------------------------------------------------
    PROCEDURE sp_crear_reserva(
        p_id_cliente     IN NUMBER,
        p_id_alojamiento IN NUMBER,
        p_id_habitacion  IN NUMBER,
        p_check_in       IN DATE,
        p_check_out      IN DATE,
        p_num_huespedes  IN NUMBER,
        p_id_reserva     OUT NUMBER
    ) IS
        v_capacidad        NUMBER(2);   -- cuantas personas caben en la habitacion
        v_cantidad_solapes NUMBER;      -- cuantas reservas se cruzan con las fechas pedidas
        v_valor            NUMBER(12);  -- valor de la estadia
    BEGIN
        -- marca de "punto de regreso": si algo sale mal volvemos aqui y no se guarda nada
        SAVEPOINT sp_crear_reserva_ini;

        -- ---- 1. Validar las fechas ----
        IF p_check_out <= p_check_in THEN
            RAISE_APPLICATION_ERROR(-20002, 'Error fechas: CHECK_OUT debe ser mayor a CHECK_IN');
        END IF;

        -- el DDL no deja mas de 30 noches por habitacion, entonces avisamos antes de que falle el INSERT
        IF (p_check_out - p_check_in) > 30 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Error fechas: Maximo 30 noches por habitacion');
        END IF;

        -- no se puede reservar para una fecha que ya paso
        IF p_check_in < TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20007, 'Error fechas: CHECK_IN no puede estar en el pasado');
        END IF;

        -- ---- 2. Validar la capacidad ----
        -- FOR UPDATE bloquea la habitacion mientras dura la transaccion: si dos personas intentan
        -- reservar la misma habitacion a la vez, la segunda espera y despues ya ve la reserva de la primera.
        SELECT capacidad INTO v_capacidad
        FROM HABITACION
        WHERE id_habitacion = p_id_habitacion AND id_alojamiento = p_id_alojamiento
        FOR UPDATE;

        IF p_num_huespedes > v_capacidad THEN
            RAISE_APPLICATION_ERROR(-20003, 'Capacidad excedida. Capacidad habitacion: ' || v_capacidad
                || ', Solicitados: ' || p_num_huespedes);
        END IF;

        -- ---- 3. Validar la disponibilidad ----
        -- Contamos las reservas de esa habitacion que se cruzan con las fechas pedidas.
        -- Dos rangos se cruzan cuando: nuevo_in < viejo_out Y nuevo_out > viejo_in.
        -- Las CANCELADAS no cuentan porque la habitacion quedo libre.
        SELECT COUNT(*) INTO v_cantidad_solapes
        FROM RESERVA_HABITACION rh
        JOIN RESERVA r ON r.id_reserva = rh.id_reserva
        WHERE rh.id_habitacion = p_id_habitacion
          AND r.estado <> 'CANCELADA'
          AND p_check_in < rh.check_out
          AND p_check_out > rh.check_in;

        IF v_cantidad_solapes > 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Habitacion no disponible en ese rango de fechas. Solape con reserva existente.');
        END IF;

        -- ---- 4. Calcular cuanto vale la estadia (noche por noche) ----
        v_valor := fn_valor_estadia(p_id_habitacion, p_check_in, p_check_out);

        -- ---- 5. Crear la reserva ----
        -- Primero la cabecera. Queda PENDIENTE hasta que se confirme. Usamos TRUNC(SYSDATE) para
        -- guardar solo la fecha sin la hora (si no, el CHECK fecha_creacion <= check_in fallaba el mismo dia).
        INSERT INTO RESERVA (id_cliente, id_alojamiento, fecha_creacion, check_in, check_out, estado)
        VALUES (p_id_cliente, p_id_alojamiento, TRUNC(SYSDATE), p_check_in, p_check_out, 'PENDIENTE')
        RETURNING id_reserva INTO p_id_reserva;   -- RETURNING nos devuelve el id que genero la base

        -- Luego el detalle: la habitacion reservada, con su valor ya calculado
        INSERT INTO RESERVA_HABITACION (id_reserva, id_alojamiento, id_habitacion, check_in, check_out, num_huespedes, valor_estadia)
        VALUES (p_id_reserva, p_id_alojamiento, p_id_habitacion, p_check_in, p_check_out, p_num_huespedes, v_valor);

        COMMIT;  -- todo salio bien, guardamos
    EXCEPTION
        -- el SELECT de capacidad no encontro la habitacion con ese alojamiento
        WHEN NO_DATA_FOUND THEN
            ROLLBACK TO sp_crear_reserva_ini;
            RAISE_APPLICATION_ERROR(-20005, 'Habitacion o alojamiento no existe');
        -- cualquier otro error (incluidos los -2000X de arriba): deshacemos y volvemos a lanzar el mismo error
        WHEN OTHERS THEN
            ROLLBACK TO sp_crear_reserva_ini;
            RAISE;
    END sp_crear_reserva;


    -- --------------------------------------------------------------------------
    -- sp_liquidacion_mensual
    -- Calcula, para cada alojamiento, cuantas noches vendio y cuanto gano en un mes
    -- (hospedaje + servicios). Solo cuenta reservas CONFIRMADAS o COMPLETADAS cuyo check-in
    -- cae en ese mes. Usa un CURSOR EXPLICITO CON PARAMETROS (c_anio y c_mes).
    -- Si el mes ya estaba liquidado, lo borra y lo calcula de nuevo.
    -- --------------------------------------------------------------------------
    PROCEDURE sp_liquidacion_mensual(p_anio IN NUMBER, p_mes IN NUMBER) IS

        -- Cursor con parametros. Hospedaje y servicios se suman en dos subconsultas SEPARADAS
        -- y luego se unen. Si se unieran directo, una reserva de 3 habitaciones contaria sus
        -- servicios 3 veces y el total saldria inflado.
        CURSOR cur_liq (c_anio NUMBER, c_mes NUMBER) IS
            SELECT a.id_alojamiento,
                   a.nombre_comercial,
                   NVL(h.total_reservas, 0) AS total_reservas,
                   NVL(h.total_noches, 0)   AS total_noches,
                   NVL(h.ing_hospedaje, 0)  AS ing_hospedaje,
                   NVL(s.ing_servicios, 0)  AS ing_servicios
            FROM ALOJAMIENTO a
            -- subconsulta 1: noches y plata de hospedaje por alojamiento
            LEFT JOIN (
                SELECT r.id_alojamiento,
                       COUNT(DISTINCT r.id_reserva)    AS total_reservas,
                       SUM(rh.check_out - rh.check_in) AS total_noches,
                       SUM(rh.valor_estadia)           AS ing_hospedaje
                FROM RESERVA r
                JOIN RESERVA_HABITACION rh ON rh.id_reserva = r.id_reserva
                WHERE EXTRACT(YEAR FROM r.check_in) = c_anio
                  AND EXTRACT(MONTH FROM r.check_in) = c_mes
                  AND r.estado IN ('CONFIRMADA', 'COMPLETADA')
                GROUP BY r.id_alojamiento
            ) h ON h.id_alojamiento = a.id_alojamiento
            -- subconsulta 2: plata de servicios por alojamiento
            LEFT JOIN (
                SELECT r.id_alojamiento,
                       SUM(rs.cantidad * rs.precio_unitario) AS ing_servicios
                FROM RESERVA r
                JOIN RESERVA_SERVICIO rs ON rs.id_reserva = r.id_reserva
                WHERE EXTRACT(YEAR FROM r.check_in) = c_anio
                  AND EXTRACT(MONTH FROM r.check_in) = c_mes
                  AND r.estado IN ('CONFIRMADA', 'COMPLETADA')
                GROUP BY r.id_alojamiento
            ) s ON s.id_alojamiento = a.id_alojamiento
            ORDER BY a.id_alojamiento;

        v_reg cur_liq%ROWTYPE;   -- una fila del cursor (tiene las mismas columnas que el SELECT)
    BEGIN
        -- si ese mes ya se habia liquidado, borramos lo anterior para volver a calcularlo
        DELETE FROM LIQUIDACION_MENSUAL WHERE anio = p_anio AND mes = p_mes;

        OPEN cur_liq(p_anio, p_mes);      -- abrimos el cursor pasandole el anio y el mes
        LOOP
            FETCH cur_liq INTO v_reg;     -- traemos una fila (un alojamiento)
            EXIT WHEN cur_liq%NOTFOUND;   -- si ya no hay mas filas, salimos

            -- guardamos la liquidacion de ese alojamiento
            INSERT INTO LIQUIDACION_MENSUAL (id_alojamiento, anio, mes, total_noches, ingresos_hospedaje,
                                             ingresos_servicios, total_liquidacion)
            VALUES (v_reg.id_alojamiento, p_anio, p_mes, v_reg.total_noches, v_reg.ing_hospedaje,
                    v_reg.ing_servicios, v_reg.ing_hospedaje + v_reg.ing_servicios);

            -- mostramos una linea por alojamiento (hay que tener SET SERVEROUTPUT ON)
            DBMS_OUTPUT.PUT_LINE('Aloj: ' || v_reg.id_alojamiento || ' Noches: ' || v_reg.total_noches
                || ' Total: ' || (v_reg.ing_hospedaje + v_reg.ing_servicios));
        END LOOP;
        CLOSE cur_liq;                    -- cerramos el cursor
        COMMIT;
    END sp_liquidacion_mensual;

END PKG_TURISMOUQ;
