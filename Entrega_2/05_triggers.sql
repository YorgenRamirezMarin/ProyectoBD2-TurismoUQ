-- Tabla de auditoria
CREATE TABLE AUDITORIA_TARIFA (
    id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR2(30) NOT NULL,
    fecha_cambio DATE NOT NULL,
    operacion VARCHAR2(10) NOT NULL CHECK (operacion IN ('INSERT','UPDATE','DELETE')),
    id_habitacion NUMBER(6),
    id_temporada NUMBER(4),
    valor_anterior NUMBER(10),
    valor_nuevo NUMBER(10),
    detalle VARCHAR2(200)
);

-- Tabla temporal para capturar OLD/NEW y luego vaciarla en el trigger de sentencia
CREATE GLOBAL TEMPORARY TABLE TMP_TARIFA_CHANGES (
    id_habitacion NUMBER(6),
    id_temporada NUMBER(4),
    valor_anterior NUMBER(10),
    valor_nuevo NUMBER(10),
    operacion VARCHAR2(10)
) ON COMMIT DELETE ROWS;

-- Trigger de fila auxiliar: captura valores antes de que el de sentencia los audite
CREATE OR REPLACE TRIGGER trg_tarifa_row_capture
BEFORE INSERT OR UPDATE OR DELETE ON TARIFA
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO TMP_TARIFA_CHANGES VALUES (:NEW.id_habitacion, :NEW.id_temporada, NULL, :NEW.valor_noche, 'INSERT');
    ELSIF UPDATING THEN
        INSERT INTO TMP_TARIFA_CHANGES VALUES (:NEW.id_habitacion, :NEW.id_temporada, :OLD.valor_noche, :NEW.valor_noche, 'UPDATE');
    ELSIF DELETING THEN
        INSERT INTO TMP_TARIFA_CHANGES VALUES (:OLD.id_habitacion, :OLD.id_temporada, :OLD.valor_noche, NULL, 'DELETE');
    END IF;
END;
/

-- DISPARADOR A NIVEL DE SENTENCIA (requisito): Auditoria de TARIFA
CREATE OR REPLACE TRIGGER trg_aud_tarifa_stmt
AFTER INSERT OR UPDATE OR DELETE ON TARIFA
BEGIN
    -- Se dispara una vez por sentencia, no por fila. Registra quien y cuando.
    FOR rec IN (SELECT * FROM TMP_TARIFA_CHANGES) LOOP
        INSERT INTO AUDITORIA_TARIFA (usuario, fecha_cambio, operacion, id_habitacion, id_temporada, valor_anterior, valor_nuevo, detalle)
        VALUES (USER, SYSDATE, rec.operacion, rec.id_habitacion, rec.id_temporada, rec.valor_anterior, rec.valor_nuevo,
                'Cambio masivo por ' || USER || ' el ' || TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS'));
    END LOOP;
END;
/

-- DISPARADOR A NIVEL DE FILA: Impedir solape de reservas
CREATE OR REPLACE TRIGGER trg_no_solape_reserva
BEFORE INSERT OR UPDATE ON RESERVA_HABITACION
FOR EACH ROW
DECLARE
    v_solapes NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_solapes
    FROM RESERVA_HABITACION rh
    JOIN RESERVA r ON r.id_reserva = rh.id_reserva
    WHERE rh.id_habitacion = :NEW.id_habitacion
      AND rh.id_reserva_hab != NVL(:OLD.id_reserva_hab, -1)
      AND r.estado IN ('CONFIRMADA','PENDIENTE')
      AND NOT (:NEW.check_out <= rh.check_in OR :NEW.check_in >= rh.check_out);

    IF v_solapes > 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'TRIGGER: Habitacion ' || :NEW.id_habitacion || ' ya ocupada en ese rango. Solape detectado.');
    END IF;
END;
